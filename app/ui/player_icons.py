_cache: dict[tuple[str, str, int], QIcon] = {}


def draw(name: str, color: str = COLOR_NORMAL, size: int = 20) -> QIcon:
    """Значок по имени. Неизвестное имя даёт пустой QIcon, а не исключение:
    отсутствующая картинка не повод ронять окно."""
    key = (name, color, size)
    cached = _cache.get(key)
    if cached is not None:
        return cached
    path = _PATHS.get(name)
    if not path:
        return QIcon()
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
           f'<path fill="{color}" d="{path}"/></svg>')
    renderer = QSvgRenderer(QByteArray(svg.encode('utf-8')))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter)
    painter.end()
    icon = QIcon(pixmap)
    _cache[key] = icon
    return icon


def pixmap(name: str, color: str = COLOR_NORMAL, size: int = 20) -> QPixmap:
    """Та же картинка, но для QLabel: значок в подписи иначе не показать."""
    icon = draw(name, color, size)
    return icon.pixmap(size, size)


def toggled(name: str, active: bool, size: int = 20) -> QIcon:
    """Значок режима: включённый подсвечен, выключенный обычный."""
    return draw(name, COLOR_ACCENT if active else COLOR_NORMAL, size)
